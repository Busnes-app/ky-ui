// Writes src/appearance-themes.css: one data-ky-preview rule per catalog theme, so
// preview cards need no inline style. Busnes values are read from tokens.css. A pair
// rule carries its light half plus the dark half under --ky-preview-dark-*.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SYSTEM_THEME, THEME_CATALOG, THEME_PAIRS, THEME_PALETTES } from '../src/themes.js';

export function busnesToken(tokensCss, id, token) {
  const block = tokensCss.match(new RegExp(`:root\\[data-ky-theme="${id}"\\] \\{([^}]+)`))?.[1];
  const value = block?.match(new RegExp(`--ky-${token}:\\s*([^;]+);`))?.[1];
  if (!value) throw new Error(`tokens.css has no --ky-${token} for ${id}`);
  return value.trim();
}

export function previewCss(tokensCss) {
  const busnes = id => ({
    bg: busnesToken(tokensCss, id, 'bg'),
    sidebar: busnesToken(tokensCss, id, 'sidebar-start'),
    ink: busnesToken(tokensCss, id, 'ink-strong'),
    accent: busnesToken(tokensCss, id, 'accent'),
  });
  const half = id => {
    const palette = THEME_PALETTES[id];
    return palette ? { bg: palette.bg, sidebar: palette.sidebarStart, ink: palette.inkStrong, accent: palette.accent } : busnes(id);
  };
  const vars = (v, prefix = '') => Object.entries(v).map(([key, value]) => `--ky-preview-${prefix}${key}: ${value};`).join(' ');
  const previews = [[SYSTEM_THEME.id, vars({ ...half('busnes-light'), sidebar: half('busnes-dark').sidebar })]];
  for (const { id } of THEME_CATALOG) previews.push([id, vars(half(id))]);
  for (const { id, light, dark } of THEME_PAIRS) previews.push([id, `${vars(half(light))} ${vars(half(dark), 'dark-')}`]);
  const rules = previews.map(([id, v]) => `[data-ky-preview="${id}"] { ${v} }`);
  return `/* Generated by scripts/appearance-themes.mjs from themes.js and tokens.css. Do not edit. */\n${rules.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = await readFile(new URL('../src/tokens.css', import.meta.url), 'utf8');
  await writeFile(new URL('../src/appearance-themes.css', import.meta.url), previewCss(tokens));
}
